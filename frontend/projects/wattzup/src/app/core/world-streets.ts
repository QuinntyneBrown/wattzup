// The street module of each scene built on the shared kit (world-kit.ts), by scene id. Each
// entry loads its street chunk on demand so riding one world never downloads the others.
import type { WorldId } from '@wattzup/api';
import type { SceneStreet, StreetFactory } from './world-kit';

type StreetCtor = new (...args: Parameters<StreetFactory>) => SceneStreet;

function lazyStreet<K extends string>(
  load: () => Promise<Record<K, StreetCtor>>,
  key: K,
): StreetLoader {
  return async () => {
    const mod = await load();
    const Ctor = mod[key]!;
    return (track, disposables) => new Ctor(track, disposables);
  };
}

export type StreetLoader = () => Promise<StreetFactory>;

